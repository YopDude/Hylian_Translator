'use strict';

const DICTIONARY_CACHE = 'hylian-kuromoji-dictionary-v1';

self.addEventListener('install', (event) => {
  event.waitUntil(self.skipWaiting());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names.filter((name) => name.startsWith('hylian-kuromoji-dictionary-') && name !== DICTIONARY_CACHE)
      .map((name) => caches.delete(name)));
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin || !/\/dict\/[^/]+\.dat\.gz$/.test(url.pathname)) return;

  event.respondWith((async () => {
    const cache = await caches.open(DICTIONARY_CACHE);
    const cached = await cache.match(request);
    if (cached) return cached;
    const response = await fetch(request);
    if (response.ok) await cache.put(request, response.clone());
    return response;
  })());
});
